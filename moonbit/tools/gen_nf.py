#!/usr/bin/env python3
"""Generate lib/nf_gen.mbt: case-preserving NFD and NFC composition tables for Greek (U+0370-03FF, U+1F00-1FFF)."""
import unicodedata as u, sys
L = ["// GENERATED by tools/gen_nf.py -- do not edit", "", "///|", "fn nfd_char(c : Char) -> String {", "  match c {"]
comp = []
for cp in list(range(0x370, 0x400)) + list(range(0x1F00, 0x2000)):
    c = chr(cp)
    if not u.category(c).startswith("L"): continue
    d = u.normalize("NFD", c)
    if d != c:
        L.append(f"    '\\u{{{cp:04X}}}' => \"" + "".join(f"\\u{{{ord(x):04X}}}" for x in d) + '"')
        if u.normalize("NFC", d) == c: comp.append((d, c))
L += ["    _ => c.to_string()", "  }", "}", "", "///|", "fn nfc_lookup(s : String) -> Char? {", "  match s {"]
for d, c in sorted(set(comp)):
    L.append("    \"" + "".join(f"\\u{{{ord(x):04X}}}" for x in d) + f"\" => Some('\\u{{{ord(c):04X}}}')")
L += ["    _ => None", "  }", "}", ""]
open(sys.argv[1], "w").write("\n".join(L) + "\n")
print(len(comp))
