#!/usr/bin/env python3
"""Generate lib/data_gen.mbt from greek_decomp.tsv + phone_bigrams.json (no text, counts only)."""
import json, sys
decomp, lm, out = sys.argv[1], sys.argv[2], sys.argv[3]
def esc(s): return "".join(c if c not in '"\\' else "\\" + c for c in s)
L = ["// GENERATED by tools/gen_data.py -- do not edit", "", "///|", "fn decomp(c : Char) -> String {", "  match c {"]
for line in open(decomp):
    a, b = line.rstrip("\n").split("\t")
    L.append(f'    \'\\u{{{a}}}\' => "' + "".join(f"\\u{{{x}}}" for x in b.split()) + '"')
L += ["    _ => c.to_string()", "  }", "}", ""]
d = json.load(open(lm))
# `_vocab_size` is not emitted: the library never reads it.
for i, s in enumerate(["modern", "koine", "attic", "erasmian"]):
    for kind in ("bigram", "unigram"):
        items = sorted(d[s][kind].items())
        L.append("///|")
        L.append(f"let lm_{kind}_{i} : Map[String, Int] = {{")
        L += [f'  "{esc(k)}": {v},' for k, v in items]
        L.append("}"); L.append("")
open(out, "w").write("\n".join(L) + "\n")
