#!/usr/bin/env python3
"""Generate lib/conf_gen.mbt from conf_tables.json (recognizer confusion counts; tables fit on public Greek text corpora)
and phone_bigrams.json (for the noisy-LM vocabulary)."""
import json, sys
ct, lm, out = json.load(open(sys.argv[1])), json.load(open(sys.argv[2])), sys.argv[3]
def esc(s): return "".join(c if c not in '"\\' else "\\" + c for c in s).replace("\t", "\\t")
S = ["modern", "byzantine", "koine", "attic", "erasmian"]
vocab = sorted({k for s in S for k in lm[s]["unigram"]} | {h for c in ct["phones"].values() for h in c})
L = ["// GENERATED by tools/gen_conf.py -- do not edit", "// " + ct["source"], ""]
for name in ("units", "preds"):
    L += ["///|", f"let ct_{name} : Map[String, Int] = {{"]
    L += [f'  "{esc(k)}\\t{esc(h)}": {n},' for k, c in ct[name].items() for h, n in c.items()]
    L += ["}", "", "///|", f"let ct_{name}_total : Map[String, Int] = {{"]
    L += [f'  "{esc(k)}": {sum(c.values())},' for k, c in ct[name].items()]
    L += ["}", ""]
L += ["///|", "let ct_phones : Map[String, Int] = {"]
L += [f'  "{esc(e)}\\t{esc(h)}": {n},' for e, c in ct["phones"].items() for h, n in c.items()]
L += ["}", "", "///|", "let ct_phones_total : Map[String, Int] = {"]
L += [f'  "{esc(e)}": {sum(c.values())},' for e, c in ct["phones"].items()]
L += ["}", "", "///|", "let nl_vocab : Array[String] = ["] + [f'  "{esc(v)}",' for v in vocab] + ["]", ""]
open(out, "w").write("\n".join(L) + "\n")
