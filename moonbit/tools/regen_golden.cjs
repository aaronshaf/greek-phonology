// Rebuild tests/ipa_golden.tsv.gz and tests/ipa_golden_data.mbt from the current JS build.
// Every 7th lexicon form (word_counts.tsv.gz order, same sampling as kl_golden) plus a
// fixed hand list of diphthong, voicing, subscript, diaeresis, geminate and cluster words.
// usage: node tools/regen_golden.cjs [--check]
const fs = require("fs");
const path = require("path");
const zlib = require("zlib");

const root = path.join(__dirname, "..");
const mb = require(path.join(root, "_build/js/release/build/api/api.js"));
const check = process.argv.includes("--check");

const words = zlib
  .gunzipSync(fs.readFileSync(path.join(root, "data/word_counts.tsv.gz")))
  .toString("utf8")
  .trim()
  .split("\n")
  .map((line) => {
    const [form, nt, lxx] = line.split("\t");
    return { form, n: Number(nt) + Number(lxx) };
  });

const VOWELS = new Set([..."αεηιουω"]);
const VOICELESS = new Set([..."πτκφθχσξψς"]);
const VOICED = new Set([..."βγδμνλρζ"]);
const CONSONANTS = new Set([..."βγδζθκλμνξπρστφχψς"]);

const nfd = (s) => s.normalize("NFD");
const base = (s) =>
  [...nfd(s)].filter((c) => {
    const cp = c.codePointAt(0);
    return cp < 0x300 || cp > 0x36f;
  }).join("");

function contexts(form, diph) {
  const b = base(form);
  const hits = [];
  let i = 0;
  while ((i = b.indexOf(diph, i)) !== -1) {
    const next = b[i + diph.length];
    let ctx = "end";
    if (next) {
      if (VOWELS.has(next)) ctx = "vowel";
      else if (VOICELESS.has(next)) ctx = "voiceless";
      else if (VOICED.has(next)) ctx = "voiced";
      else ctx = "other";
    }
    hits.push(ctx);
    i += diph.length;
  }
  return hits;
}

function hasSubscript(form, vowel) {
  const cs = [...nfd(form)];
  for (let i = 0; i < cs.length; i++) {
    if (cs[i] !== vowel) continue;
    for (let j = i + 1; j < cs.length && cs[j].codePointAt(0) >= 0x300 && cs[j].codePointAt(0) <= 0x36f; j++) {
      if (cs[j] === "\u0345") return true;
    }
  }
  return false;
}

function hasDiaeresis(form) {
  return nfd(form).includes("\u0308");
}

function hasGeminate(form) {
  const b = [...base(form)];
  for (let i = 0; i < b.length - 1; i++) {
    if (b[i] === b[i + 1] && CONSONANTS.has(b[i])) return true;
  }
  return false;
}

function take(pred, k) {
  return words
    .filter((w) => pred(w.form))
    .sort((a, b) => b.n - a.n || (a.form < b.form ? -1 : 1))
    .slice(0, k)
    .map((w) => w.form);
}

const hand = new Set();
const add = (forms) => {
  for (const f of forms) hand.add(f);
};

for (const diph of ["αυ", "ευ", "ηυ"]) {
  for (const ctx of ["end", "voiceless", "vowel", "voiced"]) {
    add(take((f) => contexts(f, diph).includes(ctx), 8));
  }
}
add(take((f) => base(f).includes("υι"), 16));
for (const v of ["α", "η", "ω"]) add(take((f) => hasSubscript(f, v), 8));
add(take((f) => base(f).includes("ωυ"), 8));
add(take(hasDiaeresis, 12));
add(take(hasGeminate, 12));
for (const cluster of ["γγ", "γκ", "μπ", "ντ"]) add(take((f) => base(f).includes(cluster), 8));

const forced = ["υἱός", "υἱοῦ", "υἱόν", "αὐτός", "εὐαγγέλιον", "θάλασσα", "ἄγγελος", "οὐρανός", "θεός", "κόσμος"];
const missing = [];
for (const f of forced) {
  if (words.some((w) => w.form === f)) hand.add(f);
  else missing.push(f);
}

const sample = [];
for (let i = 0; i < words.length; i += 7) sample.push(words[i].form);
const seen = new Set(sample);
const extra = [];
for (const w of words) {
  if (hand.has(w.form) && !seen.has(w.form)) extra.push(w.form);
}

const schemes = ["modern", "koine", "attic", "erasmian"];
const lines = ["form\tmodern\tkoine\tattic\terasmian"];
for (const form of sample.concat(extra)) {
  const cols = schemes.map((s) => mb.ipa(form, s));
  for (const c of cols) {
    if (c.includes("\t") || c.includes("\n") || c.includes("\r")) {
      throw new Error("ipa() contained a field delimiter for " + form);
    }
  }
  lines.push([form, ...cols].join("\t"));
}
const tsv = lines.join("\n") + "\n";
const gzPath = path.join(root, "tests/ipa_golden.tsv.gz");
const mbtPath = path.join(root, "tests/ipa_golden_data.mbt");
const mbt =
  "// GENERATED by tools/regen_golden.sh — do not edit.\n" +
  "// Snapshot of ipa() for every 7th lexicon form plus a diphthong/voicing hand list.\n\n" +
  "///|\n" +
  "let ipa_golden_tsv : String =\n" +
  tsv
    .replace(/\n$/, "")
    .split("\n")
    .map((line) => "  #|" + line)
    .join("\n") +
  "\n\n///|\nlet _ipa_golden_rows : Int = ipa_golden_tsv.length()\n";

if (check) {
  const have = fs.readFileSync(gzPath);
  const got = zlib.gzipSync(Buffer.from(tsv, "utf8"), { level: 9 });
  // gzip headers differ by mtime; compare uncompressed payloads
  const old = zlib.gunzipSync(have).toString("utf8");
  const data = fs.readFileSync(mbtPath, "utf8");
  const embedded = data
    .split("\n")
    .filter((line) => line.startsWith("  #|"))
    .map((line) => line.slice(4))
    .join("\n") + "\n";
  if (old !== tsv || embedded !== tsv) {
    console.error("ipa golden is stale; run tools/regen_golden.sh");
    process.exit(1);
  }
  console.log(`ipa golden ok (${sample.length} sample + ${extra.length} hand-only, ${hand.size} hand forms)`);
} else {
  fs.writeFileSync(gzPath, zlib.gzipSync(Buffer.from(tsv, "utf8"), { level: 9 }));
  fs.writeFileSync(mbtPath, mbt);
  console.log(
    `wrote ${lines.length - 1} rows (${sample.length} every-7th + ${extra.length} hand-only); hand ${hand.size}; missing forced: ${missing.join(" ") || "none"}`,
  );
  console.log(`tsv.gz ${fs.statSync(gzPath).size} bytes; mbt ${fs.statSync(mbtPath).size} bytes`);
}
