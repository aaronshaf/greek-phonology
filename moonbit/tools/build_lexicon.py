#!/usr/bin/env python3
"""Build data/greek-phonology-lexicon.bin (+ lib/lex_alpha_gen.mbt, data/word_counts.tsv.gz) from
the SBLGNT and Rahlfs LXX word forms.

usage: build_lexicon.py SBLGNT_TSV LXX_CSV
  SBLGNT_TSV: word<TAB>...<TAB>count rows (col 0 form, col 4 count)
  LXX_CSV:    eliranwong/LXX-Rahlfs-1935 01_wordlist_unicode/text_accented.csv (id<TAB>id<TAB>form)

Format (front-coded, sorted by NFD): per entry
  [shared-prefix length][flags][suffix codes...][0]
  flags bit0 = NT, bit1 = LXX, bits2-5 = frequency band (0, else floor(log2(count)) + 1, max 15)
  codes index ALPHA (1-based) over NFD characters. Grave is stored as acute.
"""
import collections, gzip, json, math, sys, unicodedata as u

def norm(w):
    w = u.normalize("NFD", w).replace("\u0300", "\u0301")
    return u.normalize("NFC", "".join(c for c in w if u.category(c)[0] in "LM"))

nt, lxx = collections.Counter(), collections.Counter()
for line in open(sys.argv[1], encoding="utf-8"):
    if line.startswith("#") or not line.strip(): continue
    p = line.rstrip("\n").split("\t")
    if norm(p[0]): nt[norm(p[0])] += int(p[4] or 0) if len(p) > 4 else 1
for line in open(sys.argv[2], encoding="utf-8"):
    p = line.rstrip("\n").split("\t")
    if len(p) >= 3 and norm(p[2]): lxx[norm(p[2])] += 1
words = sorted(set(nt) | set(lxx), key=lambda w: u.normalize("NFD", w))
alpha = sorted({c for w in words for c in u.normalize("NFD", w)})
assert len(alpha) < 250
code = {c: i + 1 for i, c in enumerate(alpha)}
buf, prev = bytearray(), []
for w in words:
    d = [code[c] for c in u.normalize("NFD", w)]
    k = 0
    while k < min(len(d), len(prev), 255) and d[k] == prev[k]: k += 1
    f = nt[w] + lxx[w]
    band = 0 if not f else min(15, int(math.log2(f)) + 1)
    buf += bytes([k, (1 if nt[w] else 0) | (2 if lxx[w] else 0) | (band << 2)]) + bytes(d[k:]) + b"\0"
    prev = d
open("data/greek-phonology-lexicon.bin", "wb").write(buf)
with gzip.open("data/word_counts.tsv.gz", "wt", encoding="utf-8", compresslevel=9) as fh:
    for w in words: fh.write(f"{w}\t{nt[w]}\t{lxx[w]}\n")
esc = "".join(f"\\u{{{ord(c):04X}}}" for c in alpha)
open("lib/lex_alpha_gen.mbt", "w").write(
    "// GENERATED by tools/build_lexicon.py -- do not edit\n\n///|\nlet lex_alpha : String = \"" + esc + "\"\n")
print(f"{len(words)} forms (NT {len(nt)}, LXX {len(lxx)}), {len(buf)} bytes, gzip {len(gzip.compress(bytes(buf), 9))}")
